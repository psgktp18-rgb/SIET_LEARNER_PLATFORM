'use client';

import React, { useState } from 'react';
import { Card, CardContent, CardHeader } from '@/components/ui/card';
import { Button } from '@/components/ui/button';
import { Badge } from '@/components/ui/badge';
import { Textarea } from '@/components/ui/textarea';
import {
  Sparkles,
  Copy,
  Check,
  Edit2,
  Bookmark,
  FileDown,
  Printer,
  ThumbsUp,
  ThumbsDown,
  Square,
  AlertCircle,
  Share2,
} from 'lucide-react';

interface AiOutputViewerProps {
  toolTitle: string;
  toolType: string;
  output: string;
  isStreaming?: boolean;
  onStop?: () => void;
  onUseInClass?: (content: string) => void;
  useInClassLabel?: string;
}

export function AiOutputViewer({
  toolTitle,
  toolType,
  output,
  isStreaming = false,
  onStop,
  onUseInClass,
  useInClassLabel = 'Use in Class',
}: AiOutputViewerProps) {
  const [copied, setCopied] = useState(false);
  const [isEditing, setIsEditing] = useState(false);
  const [editedText, setEditedText] = useState('');
  const [rating, setRating] = useState<'UP' | 'DOWN' | null>(null);
  const [saved, setSaved] = useState(false);
  const [saving, setSaving] = useState(false);

  const currentContent = isEditing ? editedText : (editedText || output);

  const handleCopy = () => {
    navigator.clipboard.writeText(currentContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleSaveToLibrary = async () => {
    if (!currentContent.trim()) return;
    setSaving(true);
    try {
      const res = await fetch('/api/ai/library', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          tool: toolType,
          title: `${toolTitle} (${new Date().toLocaleDateString()})`,
          content: currentContent,
          metadata: { rating },
        }),
      });
      if (res.ok) {
        setSaved(true);
        setTimeout(() => setSaved(false), 3000);
      }
    } catch (e) {
      console.error(e);
    } finally {
      setSaving(false);
    }
  };

  const handleExportDocx = () => {
    // Generate clean Word-compatible document
    const blob = new Blob(
      [
        `<!DOCTYPE html><html><head><meta charset="utf-8"><title>${toolTitle}</title><style>body{font-family:Arial,sans-serif;line-height:1.6;padding:24px;}h1,h2,h3{color:#004d00;}</style></head><body><h1>${toolTitle}</h1><p><em>AI-generated by Lecture Lens (SIET) · Please review before use</em></p><hr><pre style="white-space:pre-wrap;font-family:inherit;">${currentContent}</pre></body></html>`,
      ],
      { type: 'application/msword' }
    );
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${toolTitle.toLowerCase().replace(/\s+/g, '_')}.doc`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
  };

  const handleExportPdf = () => {
    const printWindow = window.open('', '_blank');
    if (!printWindow) return;
    printWindow.document.write(`
      <html>
        <head>
          <title>${toolTitle} - Lecture Lens</title>
          <style>
            body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; line-height: 1.6; padding: 40px; color: #111; }
            h1 { color: #004d00; border-bottom: 2px solid #F7E135; padding-bottom: 8px; }
            .notice { font-size: 12px; color: #666; margin-bottom: 24px; }
            pre { white-space: pre-wrap; font-family: inherit; font-size: 14px; }
          </style>
        </head>
        <body>
          <h1>${toolTitle}</h1>
          <div class="notice">Generated via Lecture Lens AI Studio · Sri Shakthi Institute of Engineering and Technology</div>
          <pre>${currentContent}</pre>
        </body>
      </html>
    `);
    printWindow.document.close();
    printWindow.focus();
    setTimeout(() => {
      printWindow.print();
    }, 250);
  };

  const handleRating = async (val: 'UP' | 'DOWN') => {
    setRating(val);
  };

  return (
    <Card className="border shadow-md overflow-hidden bg-card mt-6">
      <CardHeader className="bg-muted/40 p-3.5 border-b flex flex-row items-center justify-between flex-wrap gap-2">
        <div className="flex items-center gap-2">
          <div className="h-7 w-7 rounded-md bg-primary text-secondary flex items-center justify-center font-bold">
            <Sparkles className="h-4 w-4" />
          </div>
          <div>
            <h4 className="text-sm font-bold text-foreground">{toolTitle}</h4>
            <div className="flex items-center gap-2 mt-0.5">
              <Badge variant="outline" className="text-3xs border-amber-400 text-amber-800 bg-amber-50 dark:bg-amber-950/30">
                <AlertCircle className="h-3 w-3 mr-1" /> AI-generated, please review
              </Badge>
              {isStreaming && (
                <span className="text-2xs font-mono text-primary animate-pulse flex items-center gap-1">
                  <span className="h-2 w-2 rounded-full bg-primary animate-ping" />
                  Streaming...
                </span>
              )}
            </div>
          </div>
        </div>

        {/* Toolbar Buttons */}
        <div className="flex items-center gap-1.5 flex-wrap">
          {isStreaming && onStop && (
            <Button size="sm" variant="destructive" onClick={onStop} className="h-8 text-xs gap-1">
              <Square className="h-3.5 w-3.5" /> Stop
            </Button>
          )}

          <Button size="sm" variant="outline" onClick={handleCopy} className="h-8 text-xs gap-1">
            {copied ? <Check className="h-3.5 w-3.5 text-green-600" /> : <Copy className="h-3.5 w-3.5" />}
            {copied ? 'Copied' : 'Copy'}
          </Button>

          <Button
            size="sm"
            variant="outline"
            onClick={() => {
              if (!isEditing) setEditedText(currentContent);
              setIsEditing(!isEditing);
            }}
            className="h-8 text-xs gap-1"
          >
            <Edit2 className="h-3.5 w-3.5" />
            {isEditing ? 'Preview' : 'Edit'}
          </Button>

          <Button
            size="sm"
            variant="outline"
            onClick={handleSaveToLibrary}
            disabled={saving || !currentContent}
            className="h-8 text-xs gap-1 text-primary"
          >
            {saved ? <Check className="h-3.5 w-3.5 text-green-600" /> : <Bookmark className="h-3.5 w-3.5" />}
            {saved ? 'Saved!' : 'Save to Library'}
          </Button>

          <Button size="sm" variant="ghost" onClick={handleExportDocx} className="h-8 text-xs px-2" title="Export as Word document">
            <FileDown className="h-3.5 w-3.5" />
          </Button>

          <Button size="sm" variant="ghost" onClick={handleExportPdf} className="h-8 text-xs px-2" title="Print / PDF preview">
            <Printer className="h-3.5 w-3.5" />
          </Button>

          {onUseInClass && (
            <Button
              size="sm"
              onClick={() => onUseInClass(currentContent)}
              className="h-8 text-xs bg-primary hover:bg-primary/90 text-primary-foreground gap-1"
            >
              <Share2 className="h-3.5 w-3.5" />
              {useInClassLabel}
            </Button>
          )}
        </div>
      </CardHeader>

      <CardContent className="p-4">
        {isEditing ? (
          <div className="space-y-2">
            <Textarea
              value={editedText}
              onChange={(e: any) => setEditedText(e.target.value)}
              rows={16}
              className="font-mono text-xs leading-relaxed"
            />
            <p className="text-3xs text-muted-foreground">Editing mode active · Changes will be preserved when copying or saving.</p>
          </div>
        ) : (
          <div className="prose prose-sm dark:prose-invert max-w-none text-xs leading-relaxed whitespace-pre-wrap font-sans bg-muted/15 p-4 rounded-md border min-h-[140px]">
            {currentContent || (
              <span className="text-muted-foreground italic">Waiting for generation...</span>
            )}
            {isStreaming && (
              <span className="inline-block w-2 h-4 bg-primary ml-1 animate-pulse align-middle" />
            )}
          </div>
        )}

        {/* Thumbs Feedback */}
        <div className="mt-4 pt-3 border-t flex items-center justify-between text-2xs text-muted-foreground">
          <div className="flex items-center gap-2">
            <span>Was this output helpful?</span>
            <button
              onClick={() => handleRating('UP')}
              className={`p-1 rounded hover:bg-accent transition-colors ${
                rating === 'UP' ? 'text-green-600 font-bold' : ''
              }`}
              title="Thumbs Up"
            >
              <ThumbsUp className="h-3.5 w-3.5" />
            </button>
            <button
              onClick={() => handleRating('DOWN')}
              className={`p-1 rounded hover:bg-accent transition-colors ${
                rating === 'DOWN' ? 'text-destructive font-bold' : ''
              }`}
              title="Thumbs Down"
            >
              <ThumbsDown className="h-3.5 w-3.5" />
            </button>
            {rating && <span className="text-3xs text-green-700 ml-1">Thanks for the feedback!</span>}
          </div>

          <span className="text-3xs font-mono opacity-70">Lecture Lens AI Core</span>
        </div>
      </CardContent>
    </Card>
  );
}
